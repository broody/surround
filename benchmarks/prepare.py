#!/usr/bin/env python3
"""Generate a scorer copy and inputs directly from the tested Surround sources."""
import importlib.util
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
spec = importlib.util.spec_from_file_location("sgf_reference", ROOT / "scripts/generate_sgf_fixtures.py")
reference = importlib.util.module_from_spec(spec)
spec.loader.exec_module(reference)

# Only remove Dojo storage introspection derives; every rule/function stays exact.
source = (ROOT / "src/rules.cairo").read_text()
generated = source.replace(
    "Copy, Drop, Serde, Introspect, DojoStore, PartialEq, Debug",
    "Copy, Drop, Serde, PartialEq, Debug",
)
assert source.count("Introspect, DojoStore") == 2
def save(path, content):
    if "--check" in sys.argv:
        assert path.read_text() == content, f"Stale generated file: {path}; run prepare.py"
    else:
        path.write_text(content)


save(ROOT / "benchmarks/scoring/src/rules.cairo",
     "// Generated by benchmarks/prepare.py from src/rules.cairo; do not edit.\n" + generated)

def limbs(points):
    result = [0, 0, 0]
    for point in points:
        result[point // 128] |= 1 << (point % 128)
    return result

fixtures = []
for record in json.loads((reference.FIXTURES / "manifest.json").read_text())["games"]:
    f = reference.validate(record)
    arguments = [f["size"], f["komi"], *limbs(f["stones"]["b"]),
                 *limbs(f["stones"]["w"]), *limbs(f["dead"])]
    fixtures.append({"id": f["id"], "size": f["size"], "result": f["result"],
                     "margin_half": f["margin"], "arguments": [hex(n) for n in arguments]})
save(ROOT / "benchmarks/fixtures.json", json.dumps(fixtures, indent=2) + "\n")
print(f"Validated exact scorer and {len(fixtures)} independently checked SGF inputs")
