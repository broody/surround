#!/usr/bin/env python3
"""Measure real local Stwo proofs. Uses Scarb 2.18's bootloader target.

This is a Cairo proof benchmark, not a native SNIP-36 transaction proof.
Run prepare.py and direct.mjs first. Raw proofs and logs stay gitignored.
"""
import hashlib
import json
import os
import platform
import subprocess
import time
from datetime import datetime, timezone
from pathlib import Path

HERE = Path(__file__).resolve().parent
SCORING = HERE / "scoring"
RESULTS = HERE / "results"
FIELD = 2**251 + 17 * 2**192 + 1
ENV = {**os.environ, "RAYON_NUM_THREADS": os.environ.get("RAYON_NUM_THREADS", "8")}


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def run(arguments, log):
    """Record one process tree's wall time and peak RSS (macOS/Linux)."""
    start = time.perf_counter()
    with log.open("w") as stream:
        process = subprocess.Popen(arguments, cwd=SCORING, env=ENV,
                                   stdout=stream, stderr=subprocess.STDOUT)
        _, status, usage = os.wait4(process.pid, 0)
        process.returncode = os.waitstatus_to_exitcode(status)
    measurement = {
        "wall_seconds": time.perf_counter() - start,
        "peak_rss_bytes": usage.ru_maxrss * (1 if platform.system() == "Darwin" else 1024),
        "exit_code": process.returncode,
    }
    return measurement, log.read_text()


def require_success(result, text, label):
    if result["exit_code"] != 0:
        raise RuntimeError(f"{label} failed:\n{text[-2000:]}")


def ndjson(text):
    return [json.loads(line) for line in text.splitlines() if line.startswith("{")]


def main():
    source = (HERE.parent / "src/rules.cairo").read_text()
    expected = "// Generated by benchmarks/prepare.py from src/rules.cairo; do not edit.\n" + source.replace(
        "Copy, Drop, Serde, Introspect, DojoStore, PartialEq, Debug",
        "Copy, Drop, Serde, PartialEq, Debug",
    )
    if (SCORING / "src/rules.cairo").read_text() != expected:
        raise RuntimeError("Scorer copy is stale; run benchmarks/prepare.py")
    raw = RESULTS / "raw"
    raw.mkdir(parents=True, exist_ok=True)
    version = subprocess.check_output(["scarb", "--version"], cwd=SCORING, text=True)
    if not version.startswith("scarb 2.18.0 "):
        raise RuntimeError("This benchmark is pinned to Scarb 2.18.0")
    built, log = run(["scarb", "build"], raw / "build.log")
    require_success(built, log, "build")
    fixtures = json.loads((HERE / "fixtures.json").read_text())
    direct_file = RESULTS / "direct.json"
    direct = {r["id"]: r for r in json.loads(direct_file.read_text())["records"]}
    results = {
        "measured_at": datetime.now(timezone.utc).isoformat(),
        "kind": "Stwo Cairo bootloader proof; NOT native SNIP-36",
        "scarb": version.strip(), "platform": platform.platform(),
        "logical_cpus": os.cpu_count(), "rayon_threads": int(ENV["RAYON_NUM_THREADS"]),
        "samples_per_fixture": 1, "build_time_excluded": True,
        "source_sha256": digest(HERE.parent / "src/rules.cairo"),
        "generated_rules_sha256": digest(SCORING / "src/rules.cairo"),
        "executable_sha256": digest(SCORING / "target/dev/surround_score_bench.executable.json"),
        "fixtures_sha256": digest(HERE / "fixtures.json"),
        "direct_results_sha256": digest(direct_file), "records": [],
    }
    program_hash = None
    for fixture in fixtures:
        name = fixture["id"]
        folder = raw / name
        folder.mkdir(exist_ok=True)
        args_file = folder / "arguments.json"
        args_file.write_text(json.dumps(fixture["arguments"]) + "\n")
        executed, text = run([
            "scarb", "execute", "--no-build", "--target", "bootloader", "--output", "standard",
            "--arguments-file", str(args_file), "--print-program-output", "--print-resource-usage",
            "--json",
        ], folder / "execute.log")
        require_success(executed, text, "execute")
        events = ndjson(text)
        summary = next(e for e in events if "program_output" in e)
        # Bootloader framing: task count, task output length (including hash),
        # executable program hash, then our three output felts.
        output = [int(n) % FIELD for n in summary["program_output"].splitlines()]
        assert len(output) == 6 and output[:2] == [1, 5], "Unexpected bootloader output schema"
        if program_hash is None:
            program_hash = output[2]
        assert output[2] == program_hash, "Executable changed between proofs"
        assert output[4] - output[5] == fixture["margin_half"], "Published SGF score mismatch"
        assert list(map(str, output[3:])) == direct[name]["output"], "Direct/proved statement mismatch"
        execution = SCORING / next(e["message"] for e in events
                                   if e.get("status") == "saving output to:")
        execution_id = execution.name.removeprefix("execution")
        print(f"{name}: proving {summary['resources']['n_steps']:,} VM steps", flush=True)
        proved, text = run(["scarb", "prove", "--execution-id", execution_id, "--json"],
                           folder / "prove.log")
        require_success(proved, text, "prove")
        proof_path = execution / "proof/proof.json"
        verified, text = run(["scarb", "verify", "--proof-file", str(proof_path), "--json"],
                             folder / "verify.log")
        require_success(verified, text, "verify")
        proof = json.loads(proof_path.read_text())
        public_output = proof["claim"]["public_data"]["public_memory"]["output"]
        decoded = [sum(limb << (32 * i) for i, limb in enumerate(words))
                   for _, words in public_output]
        assert decoded == output, "Verified proof public output differs from executed score"

        # Alter a well-formed public score, preserving the rest of the proof.
        public_output[4][1][0] ^= 1
        tampered = folder / "tampered-proof.json"
        tampered.write_text(json.dumps(proof))
        rejected, text = run(["scarb", "verify", "--proof-file", str(tampered), "--json"],
                             folder / "tamper.log")
        if rejected["exit_code"] != 1 or "failed to verify proof" not in text:
            raise RuntimeError("Changed score did not produce a cryptographic verification failure")
        tampered.unlink()
        record = {
            "id": name, "size": fixture["size"], "result": fixture["result"],
            "program_hash": str(program_hash), "output": list(map(str, output[3:])),
            "resources": summary["resources"], "execute": executed, "prove": proved,
            "verify": verified, "changed_score_rejected": True,
            "proof_path": str(proof_path.relative_to(HERE.parent)),
            "proof_json_bytes": proof_path.stat().st_size, "proof_sha256": digest(proof_path),
        }
        results["records"].append(record)
        print(f"{name}: verified; prove {proved['wall_seconds']:.2f}s; "
              f"verify {verified['wall_seconds']:.3f}s; changed score rejected", flush=True)
    (RESULTS / "proofs.json").write_text(json.dumps(results, indent=2) + "\n")
    print(f"All {len(fixtures)} proofs verified; saved {RESULTS / 'proofs.json'}", flush=True)


if __name__ == "__main__":
    main()
