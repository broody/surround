// Writes ratings/src/tests/vectors.cairo from the SDK's integer rating update
// (offchain/sdk/src/rating.mjs), so SurroundRatings' Cairo math is checked bit
// for bit against the reference: edge cases, then a seeded sequence of games
// among players from every starting band. Run after changing either side.
import { execFileSync } from 'node:child_process';
import { writeFile } from 'node:fs/promises';
import * as r from './sdk/src/rating.mjs';

const T0 = 1_700_000_000n;
const rating = x => `Rating { mu: ${x.mu}, phi: ${x.phi}, last: ${x.last} }`;
const at = (mu, phi, last) => ({ mu, phi, last });

// [label, black, white, result, t]
const cases = [
  ['both new, equal bands', r.start(3), r.start(3), 2, T0],
  ['new 23k beats new 1k', r.start(1), r.start(4), 2, T0],
  ['new player draws an established one', r.start(2), at(r.MU_T[14], r.ONE / 2n, T0 - 86400n), 1, T0],
  ['established equals', at(r.MU_T[25], r.ONE / 3n, T0 - 3600n), at(r.MU_T[25], r.ONE / 3n, T0 - 7200n), 0, T0],
  ['favourite wins', at(r.MU_T[33], r.ONE / 4n, T0 - 86400n), at(r.MU_T[18], r.ONE / 4n, T0 - 86400n), 2, T0],
  ['huge upset', at(r.MU_MIN, r.ONE / 4n, T0 - 86400n), at(r.MU_MAX, r.ONE / 4n, T0 - 86400n), 2, T0],
  ['clamped at both ends', at(r.MU_MAX, r.PHI0, T0 - 86400n), at(r.MU_MIN, r.PHI0, T0 - 86400n), 2, T0],
  ['one year idle', at(r.MU_T[28], r.ONE / 5n, T0 - 365n * 86400n), at(r.MU_T[28], r.ONE / 5n, T0 - 60n), 0, T0],
  ['sixty years idle (idle cap)', at(r.MU_T[10], r.MIN_PHI, 0n), at(r.MU_T[10], r.ONE / 2n, T0 - 60n), 2, T0],
  ['rated out of order', at(r.MU_T[20], r.ONE / 2n, T0 + 5000n), at(r.MU_T[21], r.ONE / 2n, T0 + 9000n), 2, T0],
  ['same second', at(r.MU_T[20], r.ONE / 2n, T0), at(r.MU_T[20], r.ONE / 2n, T0), 1, T0],
  ['minimum deviation', at(r.MU_T[30], r.MIN_PHI, T0), at(r.MU_T[30], r.MIN_PHI, T0), 2, T0],
  ['dan half-life band', at(r.MU_T[31], r.ONE / 2n, T0 - 30n * 86400n), at(r.MU_T[31], r.ONE, T0 - 3n * 86400n), 0, T0],
  ['kyu half-life band', at(r.MU_T[12], r.ONE / 2n, T0 - 30n * 86400n), at(r.MU_T[22], r.ONE, T0 - 3n * 86400n), 2, T0],
];

// A seeded sequence: 24 players, 6 per band, 200 games over about a year.
let seed = 0x5eed;
const next = () => { seed ^= seed << 13; seed >>>= 0; seed ^= seed >> 17; seed ^= seed << 5; seed >>>= 0; return seed / 2 ** 32; };
const bands = Array.from({ length: 24 }, (_, i) => 1 + (i % 4));
const players = bands.map(r.start);
const games = [];
let t = T0;
for (let i = 0; i < 200; i++) {
  const a = Math.floor(next() * 24), b = (a + 1 + Math.floor(next() * 23)) % 24;
  t += BigInt(Math.floor(next() ** 3 * 20 * 86400));
  const result = next() < 0.03 ? 1 : next() < 0.5 ? 2 : 0;
  const out = r.update(players[a], players[b], result, t);
  games.push({ a, b, result, t, ...out });
  players[a] = out.black; players[b] = out.white;
}

const out = [
  '// Generated by offchain/generate-rating-vectors.mjs from offchain/sdk/src/rating.mjs.',
  '// Do not edit by hand.',
  'use crate::math::Rating;',
  '',
  '#[derive(Copy, Drop)]',
  'pub struct Case {',
  '    pub black: Rating,',
  '    pub white: Rating,',
  '    pub result: u8,',
  '    pub t: u64,',
  '    pub black_out: Rating,',
  '    pub white_out: Rating,',
  '    pub p: i128,',
  '}',
  '',
  '#[derive(Copy, Drop)]',
  'pub struct Game {',
  '    pub black: u32,',
  '    pub white: u32,',
  '    pub result: u8,',
  '    pub t: u64,',
  '    pub black_out: Rating,',
  '    pub white_out: Rating,',
  '    pub p: i128,',
  '}',
  '',
  'pub fn cases() -> Array<Case> {',
  '    array![',
  ...cases.map(([label, black, white, result, time]) => {
    const u = r.update(black, white, result, time);
    return [
      `        // ${label}`,
      `        Case {`,
      `            black: ${rating(black)},`,
      `            white: ${rating(white)},`,
      `            result: ${result},`,
      `            t: ${time},`,
      `            black_out: ${rating(u.black)},`,
      `            white_out: ${rating(u.white)},`,
      `            p: ${u.p},`,
      `        },`,
    ].join('\n');
  }),
  '    ]',
  '}',
  '',
  '/// Starting band of each player in `sequence`.',
  `pub fn bands() -> Span<u8> {`,
  `    array![${bands.join(', ')}].span()`,
  '}',
  '',
  'pub fn sequence() -> Array<Game> {',
  '    array![',
  ...games.map(g => [
    `        Game {`,
    `            black: ${g.a},`,
    `            white: ${g.b},`,
    `            result: ${g.result},`,
    `            t: ${g.t},`,
    `            black_out: ${rating(g.black)},`,
    `            white_out: ${rating(g.white)},`,
    `            p: ${g.p},`,
    `        },`,
  ].join('\n')),
  '    ]',
  '}',
  '',
  '/// (μ, rank in tenths) at the table points, midpoints and the clamp limits.',
  'pub fn ranks() -> Array<(i128, u16)> {',
  '    array![',
  ...[...r.MU_T, ...r.MU_T.slice(0, 39).map((m, i) => (m + r.MU_T[i + 1]) / 2n), 0n, r.MU_MIN, r.MU_MAX, r.MU_MIN - 1n]
    .map(mu => `        (${mu}, ${r.rankTenths(mu)}),`),
  '    ]',
  '}',
  '',
];
await writeFile(new URL('../ratings/src/tests/vectors.cairo', import.meta.url), out.join('\n'));
execFileSync('scarb', ['fmt'], { cwd: new URL('../ratings/', import.meta.url) });
console.log(`wrote ${cases.length} cases and a ${games.length}-game sequence`);
